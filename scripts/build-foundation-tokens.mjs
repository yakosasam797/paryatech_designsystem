import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'tokens/foundations.json');
const outputPath = path.join(root, 'src/styles/tokens/foundations.css');
const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const checkOnly = process.argv.includes('--check');

const numericGroups = ['spacing', 'radius', 'sizing', 'border', 'opacityFocus'];
const flatNumeric = numericGroups.flatMap((group) => source[group]);
const allCssNames = [
  ...flatNumeric.map((token) => token.css),
  ...source.elevation.map((token) => token.css),
  ...source.responsive.tokens.map((token) => token.css),
];

const duplicates = allCssNames.filter((name, index) => allCssNames.indexOf(name) !== index);
if (duplicates.length) throw new Error(`Duplicate CSS tokens: ${[...new Set(duplicates)].join(', ')}`);

for (const token of flatNumeric) {
  if (!token.name || !token.css?.startsWith('--') || !Number.isFinite(token.value) || !token.description) {
    throw new Error(`Invalid numeric token: ${JSON.stringify(token)}`);
  }
}

for (const style of source.typographyStyles) {
  if (!['Onest', 'Public Sans'].includes(style.family)) {
    throw new Error(`${style.name} uses forbidden font family ${style.family}`);
  }
}

const px = (token) => token.unit === 'number' ? String(token.value) : `${token.value}px`;
const lines = [
  '/* AUTO-GENERATED by scripts/build-foundation-tokens.mjs. Do not edit directly. */',
  '/* Source: Figma geometry, typography, responsive, elevation and focus systems. */',
  '',
  ':root {',
];

for (const group of numericGroups) {
  lines.push(`  /* ${group} */`);
  for (const token of source[group]) lines.push(`  ${token.css}: ${px(token)};`);
}

lines.push('  /* typography families */');
lines.push("  --type-family-heading: 'Onest', system-ui, sans-serif;");
lines.push("  --type-family-ui: 'Public Sans', system-ui, sans-serif;");
lines.push("  --type-family-data: 'Public Sans', system-ui, sans-serif;");

for (const token of source.elevation) lines.push(`  ${token.css}: ${token.value};`);

const compact = Object.fromEntries(source.responsive.tokens.map((token) => [token.css, token.values[0]]));
for (const [name, value] of Object.entries(compact)) lines.push(`  ${name}: ${value}px;`);
lines.push('}');

for (const style of source.typographyStyles) {
  const letterSpacing = style.letterUnit === '%' ? `${style.letterSpacing / 100}em` : `${style.letterSpacing}px`;
  lines.push('', `.${style.className} {`);
  lines.push(`  font-family: ${style.family === 'Onest' ? 'var(--type-family-heading)' : style.name.startsWith('Data/') ? 'var(--type-family-data)' : 'var(--type-family-ui)'};`);
  lines.push(`  font-size: ${style.size}px;`);
  lines.push(`  font-weight: ${style.weight};`);
  lines.push(`  line-height: ${style.lineHeight}px;`);
  lines.push(`  letter-spacing: ${letterSpacing};`);
  if (style.textTransform) lines.push(`  text-transform: ${style.textTransform};`);
  if (style.fontVariantNumeric) lines.push(`  font-variant-numeric: ${style.fontVariantNumeric};`);
  lines.push('}');
}

lines.push('', '@media (min-width: 1280px) {', '  :root {');
for (const token of source.responsive.tokens) lines.push(`    ${token.css}: ${token.values[1]}px;`);
lines.push('  }', '}');
lines.push('', '@media (min-width: 1440px) {', '  :root {');
for (const token of source.responsive.tokens) lines.push(`    ${token.css}: ${token.values[2]}px;`);
lines.push('  }', '}', '');

const generated = lines.join('\n');
if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) throw new Error('Generated foundation CSS is stale. Run npm run tokens:build.');
  console.log(`Foundation tokens verified: ${flatNumeric.length} numeric, ${source.typographyStyles.length} type styles, ${source.elevation.length} elevations, ${source.responsive.tokens.length} responsive.`);
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated ${path.relative(root, outputPath)}.`);
}
