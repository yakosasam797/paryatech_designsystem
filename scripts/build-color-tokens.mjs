import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';

const root = new URL('../', import.meta.url);
const corePath = new URL('tokens/core.color.json', root);
const semanticPath = new URL('tokens/semantic.color.json', root);
const outputPath = new URL('src/styles/tokens/colors.css', root);

const [coreSource, semanticSource] = await Promise.all([
  readFile(corePath, 'utf8').then(JSON.parse),
  readFile(semanticPath, 'utf8').then(JSON.parse),
]);

const coreByName = new Map(coreSource.tokens.map((token) => [token.name, token]));
const semanticByName = new Map(semanticSource.tokens.map((token) => [token.name, token]));

function assertUnique(tokens, field, label) {
  const values = new Set();
  for (const token of tokens) {
    if (values.has(token[field])) throw new Error(`Duplicate ${label}: ${token[field]}`);
    values.add(token[field]);
  }
}

assertUnique(coreSource.tokens, 'name', 'core token name');
assertUnique(coreSource.tokens, 'css', 'core CSS variable');
assertUnique(semanticSource.tokens, 'name', 'semantic token name');
assertUnique(semanticSource.tokens, 'css', 'semantic CSS variable');

function resolveAlias(alias, mode, seen = new Set()) {
  if (seen.has(alias)) throw new Error(`Circular color alias: ${[...seen, alias].join(' -> ')}`);
  seen.add(alias);

  const core = coreByName.get(alias);
  if (core) return { css: core.css, value: core.value };

  const semantic = semanticByName.get(alias);
  if (!semantic) throw new Error(`Unknown color alias: ${alias}`);
  const target = semantic[mode];
  return resolveAlias(target.alias, mode, seen);
}

for (const token of semanticSource.tokens) {
  for (const mode of ['light', 'dark']) {
    const resolved = resolveAlias(token[mode].alias, mode);
    if (resolved.value.toUpperCase() !== token[mode].value.toUpperCase()) {
      throw new Error(
        `${token.name} ${mode} resolves to ${resolved.value}, not ${token[mode].value}`,
      );
    }
  }
}

function declarations(tokens, valueFor) {
  return tokens.map((token) => `  ${token.css}: ${valueFor(token)};`).join('\n');
}

const coreCss = declarations(coreSource.tokens, (token) => token.value);
const lightCss = declarations(semanticSource.tokens, (token) => {
  const target = token.light.alias;
  return `var(${(coreByName.get(target) ?? semanticByName.get(target)).css})`;
});
const darkCss = declarations(semanticSource.tokens, (token) => {
  const target = token.dark.alias;
  return `var(${(coreByName.get(target) ?? semanticByName.get(target)).css})`;
});

const output = `/* AUTO-GENERATED by scripts/build-color-tokens.mjs. Do not edit directly. */
/* Source: Figma Core and Color variable collections. */

:root {
${coreCss}
}

:root,
[data-theme='light'] {
  color-scheme: light;
${lightCss}
}

[data-theme='dark'] {
  color-scheme: dark;
${darkCss}
}

@media (prefers-color-scheme: dark) {
  [data-theme='system'] {
    color-scheme: dark;
${darkCss}
  }
}
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('Generated color CSS is stale. Run: npm run tokens:build');
    process.exitCode = 1;
  } else {
    console.log(`Color tokens verified: ${coreSource.tokens.length} core, ${semanticSource.tokens.length} semantic.`);
  }
} else {
  await writeFile(outputPath, output);
  console.log(`Generated ${coreSource.tokens.length} core and ${semanticSource.tokens.length} semantic color tokens.`);
}
